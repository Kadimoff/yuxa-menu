export function ic(name: string, cls = 'ico'): string {
  const d = UI[name] ?? ICONS[name] ?? ICONS.star;
  return `<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true"><path d="${d}"/></svg>`;
}

export const esc = (s: unknown): string =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c] as string));

export function fmtMoney(q: number, cur = '₼'): string {
  const v = q / 100;
  const s = Number.isInteger(v) ? String(v) : v.toFixed(2).replace('.', ',');
  return `${s}\u00a0${cur}`;
}

export const img = (id: string | null, w: 240 | 480 | 720 | 1200) => (id ? `/media/${id}-${w}.webp` : '');
